/**
 * Websites (module "webhosting"): sites on weblion's own CloudPanel servers.
 *
 * Every CloudPanel server is a provider connection of type "cloudpanel". A website is a row of
 * the web space table with kind "website": one domain (plus its www counterpart), one Linux site
 * user (the SFTP/SSH login), MySQL databases, a Let's Encrypt certificate. The API reaches the
 * server through the root wrapper "weblion-clp" over SSH. Passwords are generated by the API (or
 * chosen by the user), shown once and never stored.
 *
 * Organizations create websites inside an allowance: number of sites and databases, site types,
 * one instance. There is no disk quota (CloudPanel has none); disk usage is shown for information.
 */

/** Site types CloudPanel knows (its site.type values). */
export const WEBSITE_TYPES = ['php', 'static', 'nodejs', 'python', 'reverse-proxy'] as const;
export type WebsiteType = (typeof WEBSITE_TYPES)[number];

/** Types the console creates. Python sites and reverse proxies are operator tools, never sold. */
export const CREATABLE_WEBSITE_TYPES = ['php', 'static', 'nodejs'] as const satisfies readonly WebsiteType[];
export type CreatableWebsiteType = (typeof CREATABLE_WEBSITE_TYPES)[number];

/** Types a new allowance gets unless staff choose otherwise. */
export const DEFAULT_WEBSITE_TYPES: CreatableWebsiteType[] = ['php', 'static'];

/** "webspace": a provider web space (24fire, Plesk). "website": a CloudPanel site. */
export const WEBSPACE_KINDS = ['webspace', 'website'] as const;
export type WebspaceKind = (typeof WEBSPACE_KINDS)[number];

/** Lifecycle of a website (and a website database). Web spaces are always "active". */
export const WEBSPACE_STATUSES = ['active', 'creating', 'deleting', 'error'] as const;
export type WebspaceStatus = (typeof WEBSPACE_STATUSES)[number];

/** Linux user of a website: 3 to 32 characters, lower-case letters, digits and "-". */
export const SITE_USER_PATTERN = /^[a-z][a-z0-9-]{1,30}[a-z0-9]$/;

/** Never used as site users (the server also refuses every existing Linux user). */
export const RESERVED_SITE_USERS: readonly string[] = [
  'root',
  'clp',
  'mysql',
  'nginx',
  'www-data',
  'proftpd',
  'varnish',
  'redis',
  'admin',
  'ubuntu',
  'debian',
];

/** Reserved names plus everything starting with "weblion" (the agent user, the console's own site user). */
export function isReservedSiteUser(name: string): boolean {
  return RESERVED_SITE_USERS.includes(name) || name.startsWith('weblion');
}

/** MySQL database (and user) name: at most 32 characters (MySQL user name limit). */
export const WEBSITE_DB_NAME_PATTERN = /^[a-z][a-z0-9_]{1,31}$/;
/** What the user types after the fixed prefix "<prefix>_". */
export const WEBSITE_DB_SUFFIX_PATTERN = /^[a-z0-9][a-z0-9_]{0,14}$/;
export const WEBSITE_DB_PREFIX_MAX = 16;

/**
 * Passwords for site users and database users. They only travel on stdin of chpasswd and the
 * mysql client, never through clpctl, but quotes, "$", ":", "\", "`", "(", ")", "&" and spaces
 * are refused anyway (they break clpctl and shell-based tools customers may use).
 */
export const WEBSITE_PASSWORD_PATTERN = /^[A-Za-z0-9!#%*+,\-./;<=>?@^_{|}~]{12,128}$/;

export const PHP_VERSION_PATTERN = /^\d\.\d$/;
/** Node.js LTS majors CloudPanel installs with nvm. */
export const NODEJS_VERSIONS = ['12', '14', '16', '18', '20', '22', '24'] as const;
/** Vhost template names as CloudPanel lists them, e.g. "WordPress", "Laravel 13", "PrestaShop 1.7". */
export const WEBSITE_TEMPLATE_PATTERN = /^[A-Za-z0-9][A-Za-z0-9 ._-]{0,40}$/;

/** ASCII (punycode, lower case) domain of a website, or null: same rules as mail domains. */
export function websiteDomainAscii(input: string): string | null {
  return mailDomainAscii(input);
}

/** "www.shop.ch" ↔ "shop.ch": CloudPanel serves (and redirects) both, certificates cover both. */
export function wwwCounterpart(domain: string): string {
  return domain.startsWith('www.') ? domain.slice(4) : `www.${domain}`;
}

/**
 * Site user suggested for an ASCII domain: without "www.", dots to "-", other characters
 * dropped, at most 24 characters, starting with a letter ("w" prepended otherwise):
 * "www.mueller-shop.ch" gives "mueller-shop-ch". IDN domains give their punycode labels with
 * runs of "-" collapsed ("xn--mller-kva.ch" gives "xn-mller-kva-ch"); the user can edit it.
 */
export function suggestSiteUser(domain: string): string {
  let base = domain
    .toLowerCase()
    .replace(/^www\./, '')
    .replace(/\./g, '-')
    .replace(/[^a-z0-9-]/g, '');
  base = base.replace(/-+/g, '-').replace(/^-+|-+$/g, '');
  if (!/^[a-z]/.test(base)) base = `w${base}`;
  base = base.slice(0, 24).replace(/-+$/, '');
  return base.length >= 3 ? base : `site-${base}`.slice(0, 24);
}

/** Prefix of a website's databases: site user with "-" as "_", at most 16 characters, e.g. "shop_mueller". */
export function websiteDatabasePrefix(siteUser: string): string {
  return siteUser.replace(/-/g, '_').slice(0, WEBSITE_DB_PREFIX_MAX).replace(/_+$/, '');
}

/** Full database name for a suffix, or null when the result is not a valid name. */
export function websiteDatabaseName(siteUser: string, suffix: string): string | null {
  if (!WEBSITE_DB_SUFFIX_PATTERN.test(suffix)) return null;
  const name = `${websiteDatabasePrefix(siteUser)}_${suffix}`;
  return WEBSITE_DB_NAME_PATTERN.test(name) ? name : null;
}

/** Problems of a chosen password, for form hints ("length", "characters"). Empty = fine. */
export function websitePasswordIssues(password: string): ('length' | 'characters')[] {
  const issues: ('length' | 'characters')[] = [];
  if (password.length < 12 || password.length > 128) issues.push('length');
  if (!/^[A-Za-z0-9!#%*+,\-./;<=>?@^_{|}~]*$/.test(password)) issues.push('characters');
  return issues;
}

export interface WebsiteCertificate {
  /** CloudPanel's certificate type as stored (values not documented). */
  type: string | null;
  /** Issued by Let's Encrypt as far as the console knows (it issued it, or the issuer says so). */
  letsEncrypt: boolean | null;
  /** ISO time. */
  expiresAt: string | null;
}

/** Facts of a CloudPanel site, stored in webspaces.info.site. */
export interface WebsiteFacts {
  type: WebsiteType;
  /** Linux user = SFTP/SSH login. */
  siteUser: string;
  /** /home/<siteUser> */
  homeDirectory: string;
  /** Absolute web root, e.g. /home/shop/htdocs/shop.ch or .../public. */
  webRoot: string | null;
  /** Vhost template ("WordPress", "Generic"), null for static and Node.js sites. */
  application: string | null;
  phpVersion: string | null;
  nodejsVersion: string | null;
  /** Node.js/Python app port. */
  appPort: number | null;
  certificate: WebsiteCertificate | null;
  /** Number of databases at the last read. */
  databases: number;
  /** Files of the home directory, measured every 6 h on the server. */
  diskBytes: number | null;
  /** Sum of the website's databases. */
  databaseBytes: number | null;
  usageMeasuredAt: string | null;
  /** When CloudPanel created the site (null on old panels). */
  createdAt: string | null;
}

/** How customers reach the files. Port 22, SFTP and SSH with the same login. */
export interface WebsiteAccess {
  host: string;
  port: number;
  username: string;
  homeDirectory: string;
  webRoot: string | null;
}

